export const LANGUAGES = {
  en: { name: 'English', dir: 'ltr', table: en },
  ar: { name: 'العربية', dir: 'rtl', table: ar },
  es: { name: 'Español', dir: 'ltr', table: es },
};

let current = 'en';

export function setLanguage(lang) {
  current = LANGUAGES[lang] ? lang : 'en';
  return LANGUAGES[current];
}

export const getLanguage = () => current;

function lookup(table, path) {
  return path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), table);
}

export function t(key, vars) {
  let s = lookup(LANGUAGES[current].table, key);
  if (s === undefined) s = lookup(en, key);
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

/** Apply translations to static markup. */
export function translateDom(root = document) {
  const { dir } = LANGUAGES[current];
  document.documentElement.lang = current;
  document.documentElement.dir = dir;
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    });
  });
}

export function uvLevel(uv) {
  if (typeof uv !== 'number') return null;
  if (uv < 3) return 'low';
  if (uv < 6) return 'moderate';
  if (uv < 8) return 'high';
  if (uv < 11) return 'veryHigh';
  return 'extreme';
}
